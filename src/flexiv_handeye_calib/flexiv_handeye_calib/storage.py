# human readable report
# --------------------------------------------------------------------------- #
def format_report(result: SolveResult, parent_frame: str = "", child_frame: str = "") -> str:
    lines = []
    if parent_frame or child_frame:
        lines.append(f"frames      : {parent_frame} -> {child_frame}")
    lines.append(f"method      : {result.method}")
    lines.append(f"samples     : {int(result.metrics['samples'])} used, "
                 f"{int(result.metrics['outliers'])} rejected")
    if result.outliers:
        lines.append(f"outliers    : {result.outliers}")
    lines.append(
        f"residual    : {result.metrics['translation_rms_mm']:.2f} mm rms / "
        f"{result.metrics['translation_max_mm']:.2f} mm max, "
        f"{result.metrics['rotation_rms_deg']:.3f} deg rms / "
        f"{result.metrics['rotation_max_deg']:.3f} deg max"
    )
    loo_t = result.metrics.get("loo_translation_rms_mm", float("nan"))
    loo_r = result.metrics.get("loo_rotation_rms_deg", float("nan"))
    if math.isfinite(loo_t):
        lines.append(f"leave-one-out: {loo_t:.2f} mm rms, {loo_r:.3f} deg rms")
    lines.append(
        f"rotation diversity: max {result.metrics['max_relative_rotation_deg']:.1f} deg, "
        f"mean {result.metrics['mean_relative_rotation_deg']:.1f} deg"
    )
    lines.append(
        f"consistency : {result.metrics.get('rotation_consistency_deg', float('nan')):.2f} deg "
        f"(max {result.metrics.get('rotation_consistency_max_deg', float('nan')):.2f})"
        f"  |  axis spread {result.metrics.get('rotation_axis_spread_deg', float('nan')):.1f} deg"
    )
    if result.method_spread:
        spread = max(v["translation_mm"] for v in result.method_spread.values())
        spread_r = max(v["rotation_deg"] for v in result.method_spread.values())
        lines.append(f"method spread : {spread:.2f} mm, {spread_r:.3f} deg")
    rpy = [math.degrees(v) for v in geom.matrix_to_euler(geom.rotation_of(result.X))]
    xyz = geom.translation_of(result.X)
    lines.append(
        "result      : xyz=[{:.4f}, {:.4f}, {:.4f}] m  rpy=[{:.2f}, {:.2f}, {:.2f}] deg".format(
            xyz[0], xyz[1], xyz[2], rpy[0], rpy[1], rpy[2]
        )
    )
    if result.message != "ok":
        lines.append(f"warning     : {result.message}")
    return "\n".join(lines)


def verdict(result: SolveResult) -> str:
    """A blunt pass/fail line for the operator."""
    t = result.metrics["translation_rms_mm"]
    r = result.metrics["rotation_rms_deg"]
    loo = result.metrics.get("loo_translation_rms_mm", float("nan"))
    if not math.isfinite(t):
        return "UNKNOWN"
    if t <= 2.0 and r <= 0.5:
        grade = "GOOD"
    elif t <= 5.0 and r <= 1.0:
        grade = "ACCEPTABLE"
    else:
        grade = "POOR"
    if math.isfinite(loo) and loo > max(5.0, 2.5 * t):
        grade += " (leave-one-out much worse than fit: likely overfitting / too few poses)"
    return grade
