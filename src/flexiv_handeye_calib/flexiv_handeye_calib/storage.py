"""Persistence: sample files (json) and the calibration result (yaml)."""

from __future__ import annotations

import json
import math
import os
from datetime import datetime, timezone
from typing import Dict, List, Sequence

import yaml

from . import geometry as geom
from .solver import HandEyeSample, SolveResult


# --------------------------------------------------------------------------- #
# samples
# --------------------------------------------------------------------------- #
def save_samples(path: str, samples: Sequence[HandEyeSample], meta: Dict | None = None) -> None:
    directory = os.path.dirname(os.path.abspath(path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    payload = {
        "version": 1,
        "saved_at": datetime.now(timezone.utc).isoformat(),
        "meta": meta or {},
        "samples": [s.to_dict() for s in samples],
    }
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2)
    os.replace(tmp, path)


def load_samples(path: str):
    with open(path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    samples = [HandEyeSample.from_dict(item) for item in payload.get("samples", [])]
    return samples, payload.get("meta", {})


# --------------------------------------------------------------------------- #
# result
# --------------------------------------------------------------------------- #
def _clean(value: float) -> float | None:
    value = float(value)
    return None if not math.isfinite(value) else round(value, 6)


def build_calibration(
    result: SolveResult,
    robot_sn: str,
    parent_frame: str,
    child_frame: str,
    calibration_type: str = "eye_in_hand",
) -> dict:
    X = result.X
    quat = geom.matrix_to_quat(geom.rotation_of(X))
    rpy = geom.matrix_to_euler(geom.rotation_of(X))
    xyz = geom.translation_of(X)
    metrics = {key: _clean(value) for key, value in result.metrics.items()}
    metrics["samples"] = int(result.metrics["samples"])
    metrics["outliers"] = int(result.metrics["outliers"])
    metrics["method"] = result.method
    metrics["outliers_rejected"] = result.outliers
    return {
        "handeye_calibration": {
            "type": calibration_type,
            "robot_sn": robot_sn,
            "parent_frame": parent_frame,
            "child_frame": child_frame,
            "xyz": [round(float(v), 9) for v in xyz],
            "rpy": [round(float(v), 9) for v in rpy],
            "quaternion": [round(float(v), 9) for v in quat],
            "matrix": [[round(float(v), 9) for v in row] for row in X.tolist()],
            "quality": metrics,
            "generated_at": datetime.now(timezone.utc).isoformat(),
        },
        "target_frame": {
            "pose_in_parent": [[round(float(v), 9) for v in row] for row in result.Y.tolist()],
        },
    }


def write_calibration_yaml(path: str, calibration: dict) -> None:
    directory = os.path.dirname(os.path.abspath(path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    header = (
        "# Hand-eye calibration generated by flexiv_handeye_calib.\n"
        "# xyz [m] and rpy [rad] are the transform parent_frame -> child_frame,\n"
        "# i.e. child pose expressed in parent, matching tf2 static_transform_publisher.\n"
    )
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write(header)
        yaml.safe_dump(calibration, handle, sort_keys=False, allow_unicode=True)
    os.replace(tmp, path)


